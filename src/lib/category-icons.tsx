const iconMap = new Map(categoryIconOptions.map((option) => [option.key, option.icon]));

export function CategoryIcon({ name, size = 18, className }: { name?: string | null; size?: number; className?: string }) {
  const Icon = (name && iconMap.get(name)) || CircleHelp;
  return createElement(Icon, { size, className, "aria-hidden": true });
}

export function IconPicker({ value, onChange, language }: { value: string; onChange: (value: string) => void; language: "fr" | "en" }) {
  return (
    <div className="grid max-h-44 grid-cols-6 gap-2 overflow-y-auto rounded-xl border border-yahro-border bg-[#fafaf7] p-2 [scrollbar-width:none] [&::-webkit-scrollbar]:hidden dark:border-white/10 dark:bg-[#181914] sm:grid-cols-8">
      {categoryIconOptions.map((option) => {
        const Icon = option.icon;
        const label = language === "fr" ? option.fr : option.en;
        return <button key={option.key} type="button" onClick={() => onChange(option.key)} className={`grid aspect-square place-items-center rounded-lg transition-all ${value === option.key ? "bg-[#dcebc5] text-[#405729] ring-2 ring-[#769450]/30 dark:bg-[#35452a] dark:text-[#d7edba]" : "bg-white text-[var(--yahro-muted)] hover:bg-[#eef3e7] dark:bg-white/5 dark:text-[#b8bab2] dark:hover:bg-white/10"}`} title={label} aria-label={label}><Icon size={17} /></button>;
      })}
    </div>
  );
}
